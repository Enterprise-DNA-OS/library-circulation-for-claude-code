-- Preserve insertion order for requests sharing a calendar date, including import rows.
ALTER TABLE holds ADD COLUMN queue_order bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE;
CREATE OR REPLACE VIEW hold_queue AS
 SELECT h.id,t.code title_code,t.name title,b.code borrower,b.name borrower_name,br.code pickup_branch,h.requested_on,h.state,c.barcode,h.pickup_until,
 row_number() OVER(PARTITION BY h.title_id ORDER BY h.requested_on,h.queue_order) queue_position
 FROM holds h JOIN titles t ON t.id=h.title_id JOIN borrowers b ON b.id=h.borrower_id JOIN branches br ON br.id=h.branch_id LEFT JOIN copies c ON c.id=h.copy_id
 WHERE h.state IN ('waiting','ready');
REVOKE ALL ON SEQUENCE holds_queue_order_seq FROM PUBLIC;
